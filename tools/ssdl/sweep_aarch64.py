#!/usr/bin/env python3
"""Round-trip every AArch64 scheduling model through SSDL.

AArch64 has 31 ``SchedMachineModel`` records and 85 anonymous
``ProcessorModel`` defs.  For each model this script

  1. transcribes the records to explicit SSDL (``from_records.py --mcpu``),
  2. lowers that SSDL back to TableGen and dumps its records,
  3. compares the dump with the in-tree model, both straight from the record
     table (``--records-json``) and through ``llvm-tblgen``,
  4. compares the processor the SSDL names with the in-tree ``-mcpu`` entry.

The generated TableGen names the target's instructions and registers (``map
[ADD]``, ``reg_is(1, WZR)``) but not their declarations: those are target
vocabulary, like ``opcode(ADD)``.  For the ``llvm-tblgen`` pass this script
synthesises a stub that declares exactly the names the model mentions, so the
*TableGen* is type-checked without pulling in AArch64.td (which would collide
with the generated feature defs).

``--check`` runs the sweep and compares it with ``data/aarch64-sched-sweep.json``
(status plus the five scheduling counts per model).
"""
from __future__ import annotations

import argparse
import concurrent.futures
import json
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

from ssdl import paths  # noqa: E402
from ssdl.census_sched import llvm_commit  # noqa: E402
from ssdl.family_sweep import discover, run, sanitise  # noqa: E402

STUB = "SSDLAArch64Stub.td"
DATA = ROOT / "data/aarch64-sched-sweep.json"
FORMAT = "ssdl-aarch64-sweep-1"

SUMMARY_RE = re.compile(
    r"(\d+) writes, (\d+) reads, (\d+) variants, (\d+) InstRW, (\d+) resources"
)


@dataclass
class Result:
    model: str
    status: str
    detail: str = ""
    summary: dict[str, int] = field(default_factory=dict)

    def entry(self) -> dict:
        return {"status": self.status, **self.summary}


def stub_text(instrs: set[str], regs: set[str], tiis: set[str]) -> str:
    lines = [
        "// Generated by tools/ssdl/sweep_aarch64.py: the names this model",
        "// mentions, declared so llvm-tblgen can type-check the scheduling",
        "// records without the real target description.",
        'include "llvm/Target/Target.td"',
        "",
        "def SSDLStubInstrInfo : InstrInfo;",
        "def SSDLStub : Target { let InstructionSet = SSDLStubInstrInfo; }",
        "",
    ]
    lines += [f"def {name} : Instruction;" for name in sorted(instrs)]
    lines += [f'def {name} : Register<"{name.lower()}">;' for name in sorted(regs)]
    lines += [
        f'def {name} : TIIPredicate<"{name}", MCReturnStatement<TruePred>>;'
        for name in sorted(tiis)
    ]
    return "\n".join(lines) + "\n"


def tblgen_records(
    tblgen: str,
    llvm_src: Path,
    td: Path,
    rec: Path,
    stub: Path,
) -> None:
    """Dump the TD's records, growing the stub until tblgen accepts it."""
    instrs: set[str] = set()
    regs: set[str] = set()
    tiis: set[str] = set()
    for _ in range(2000):
        stub.write_text(stub_text(instrs, regs, tiis), encoding="utf-8")
        proc = subprocess.run(
            [
                tblgen,
                "-print-records",
                "-I",
                str(llvm_src / "include"),
                "-I",
                str(stub.parent),
                "-o",
                str(rec),
                str(td),
            ],
            capture_output=True,
            text=True,
        )
        if proc.returncode == 0:
            return
        err = proc.stderr
        # The model itself may define the name (a transcribed TII predicate);
        # then the stub must not.
        match = re.search(r"def already exists: (\w+)", err)
        if match:
            name = match.group(1)
            for pool in (instrs, regs, tiis):
                pool.discard(name)
            continue
        match = re.search(r"Variable not defined: '(\w+)'", err)
        if match:
            instrs.add(match.group(1))
            continue
        match = re.search(
            r"Value specified for template argument '\S+' is of type \w+; "
            r"expected type (\w+): (\w+)",
            err,
        )
        if match:
            expected, name = match.group(1), match.group(2)
            for pool in (instrs, regs, tiis):
                pool.discard(name)
            if "Register" in expected:
                regs.add(name)
            elif "MCInstPredicate" in expected or "MCStatement" in expected:
                tiis.add(name)
            elif "Instruction" in expected:
                instrs.add(name)
            else:
                raise SystemExit(f"{td}: cannot stub {name!r} ({expected})\n{err}")
            continue
        raise SystemExit(f"{td}: llvm-tblgen failed\n{err}")
    raise SystemExit(f"{td}: stub did not converge")


def run_model(item: dict, args: argparse.Namespace) -> Result:
    model = item["model"]
    cpu = item["processor_name"]
    instance = sanitise(cpu)
    out = args.out / sanitise(model)
    out.mkdir(parents=True, exist_ok=True)
    ssdl = out / "model.ssdl"
    td = out / "model.td"
    records_json = out / "model.json"
    rec = out / "generated.rec"
    stub = out / STUB
    py = sys.executable
    from_records = [
        py,
        str(ROOT / "tools/ssdl/from_records.py"),
        str(args.records),
        "--model",
        model,
        "--machine",
        cpu,
        "--mcpu",
        cpu,
        "-o",
        str(ssdl),
    ]
    proc = run(from_records, ROOT)
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip().splitlines()
        return Result(model, "FAIL", detail[0] if detail else "from_records failed")
    proc = run(
        [
            py,
            str(ROOT / "tools/ssdl/emit_td.py"),
            str(ssdl),
            "--syntax",
            "ir",
            "--target",
            "aarch64",
            "--target-include",
            STUB,
            "--records-json",
            str(records_json),
            "-o",
            str(td),
        ],
        ROOT,
    )
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip().splitlines()
        return Result(model, "FAIL", detail[0] if detail else "emit failed")

    common = [
        str(args.records),
        "--in-model",
        model,
        "--gen-model",
        instance + "Model",
        "--in-mcpu",
        cpu,
        "--gen-processor",
        instance,
    ]
    # Straight from the record table: the claim does not depend on llvm-tblgen.
    steps = [
        [
            py,
            str(ROOT / "tools/ssdl/equiv.py"),
            *common,
            str(records_json),
            "--target",
            "aarch64",
            "--llvm-src",
            str(args.llvm_src),
        ]
    ]
    if args.tblgen is not None:
        try:
            tblgen_records(args.tblgen, args.llvm_src, td, rec, stub)
        except SystemExit as exc:
            return Result(model, "FAIL", str(exc).splitlines()[0])
        steps.append(
            [
                py,
                str(ROOT / "tools/ssdl/equiv.py"),
                *common,
                str(rec),
            ]
        )
    last = ""
    for cmd in steps:
        proc = run(cmd, ROOT)
        if proc.returncode != 0:
            detail = (proc.stderr or proc.stdout).strip().splitlines()
            return Result(model, "FAIL", detail[0] if detail else "equiv failed")
        last = proc.stdout
    (out / "equiv.txt").write_text(last, encoding="utf-8")
    numbers = SUMMARY_RE.search(last)
    summary = {}
    if numbers:
        keys = ("writes", "reads", "variants", "instrw", "resources")
        summary = {key: int(value) for key, value in zip(keys, numbers.groups())}
    if "records match" not in last:
        detail = next(
            (line for line in last.splitlines() if line.startswith("MISMATCH")),
            "no match",
        )
        return Result(model, "MISMATCH", detail, summary)
    return Result(model, "match", "", summary)


def load_data(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def compare_data(table: dict, results: list[Result]) -> list[str]:
    problems: list[str] = []
    if table.get("format") != FORMAT:
        problems.append(f"data format is {table.get('format')!r}, expected {FORMAT!r}")
    expected = table.get("models", {})
    actual = {result.model: result.entry() for result in results}
    for model in sorted(set(expected) | set(actual)):
        if model not in expected:
            problems.append(f"{model}: not in the checked-in table")
        elif model not in actual:
            problems.append(f"{model}: missing from the run")
        elif expected[model] != actual[model]:
            problems.append(
                f"{model}: table {expected[model]} != run {actual[model]}"
            )
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--records",
        type=Path,
        default=paths.records_path("aarch64"),
        help="AArch64 record dump (default: $SSDL_CACHE/aarch64.rec)",
    )
    ap.add_argument("--llvm-src", type=Path, default=paths.llvm_src())
    ap.add_argument("--tblgen", default=paths.tblgen())
    ap.add_argument("--out", type=Path, default=paths.CACHE / "aarch64-sweep")
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--only", nargs="*")
    ap.add_argument(
        "--data",
        type=Path,
        default=DATA,
        help=f"checked-in table (default: {DATA.relative_to(ROOT)})",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="run the sweep and compare it with --data",
    )
    ap.add_argument(
        "--update-data",
        action="store_true",
        help="write the current run to --data",
    )
    args = ap.parse_args(argv)
    if args.llvm_src is None:
        ap.error("--llvm-src is required when SSDL_LLVM_SRC is unset")
    if not args.records.is_file():
        ap.error(
            f"{args.records} is missing; run scripts/fetch-records.sh --target aarch64"
        )
    args.out.mkdir(parents=True, exist_ok=True)

    items = discover(args.records, args.only)
    if not args.tblgen:
        print("sweep_aarch64: llvm-tblgen not found; skipping the TD pass", file=sys.stderr)
    results: list[Result] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = [pool.submit(run_model, item, args) for item in items]
        for future in concurrent.futures.as_completed(futures):
            result = future.result()
            results.append(result)
            print(f"{result.status:8s} {result.model} {result.detail}".rstrip())
    results.sort(key=lambda result: result.model)
    matched = sum(1 for result in results if result.status == "match")

    commit = llvm_commit(args.llvm_src)
    table = {
        "format": FORMAT,
        "llvm": commit,
        "models": {result.model: result.entry() for result in results},
    }
    (args.out / "results.json").write_text(
        json.dumps(table, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    lines = ["# AArch64 SSDL sweep", "", f"{matched}/{len(results)} models records match"]
    lines.append("")
    lines.append("| model | status | writes | reads | variants | InstRW | resources |")
    lines.append("|---|---|---|---|---|---|---|")
    for result in results:
        counts = result.summary
        lines.append(
            f"| `{result.model}` | {result.status} | {counts.get('writes', '')} | "
            f"{counts.get('reads', '')} | {counts.get('variants', '')} | "
            f"{counts.get('instrw', '')} | {counts.get('resources', '')} |"
        )
    (args.out / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    if args.update_data:
        args.data.write_text(
            json.dumps(table, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        print(f"wrote {args.data}")
    if args.check:
        if not args.data.is_file():
            print(f"sweep_aarch64: {args.data} is missing", file=sys.stderr)
            return 2
        problems = compare_data(load_data(args.data), results)
        for problem in problems:
            print(f"FAIL {problem}")
        return 0 if not problems else 1
    return 0 if matched == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
